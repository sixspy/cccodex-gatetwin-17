def 扫缺腿超时(conn, 最大行程秒: int, 水位事件时: str, 处理时: str) -> int:
    """水位推进后，把超最大行程秒仍在途的开腿打进旁路。"""
    n = 0
    rows = list(conn.execute("SELECT * FROM 开腿账 WHERE 状态='在途'"))
    for leg in rows:
        if 时间.差秒(leg["进站事件时"], 水位事件时) < 最大行程秒:
            continue
        if _状态翻转(conn, leg["开腿键"], "在途", "已旁路", 处理时) == 0:
            continue
        conn.execute(
            "UPDATE 刷卡点 SET 命运=? WHERE 事件编号=? AND 命运='已开腿'",
            ("已旁路", leg["进站事件编号"]),
        )
        conn.execute(
            "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
            (
                "缺腿超时",
                leg["卡号"],
                leg["进站事件编号"],
                json.dumps(
                    {
                        "开腿键": leg["开腿键"],
                        "进站事件时": leg["进站事件时"],
                        "水位": 水位事件时,
                        "最大行程秒": 最大行程秒,
                    },
                    ensure_ascii=False,
                ),
                处理时,
            ),
        )
        n += 1
    return n


def 扫日界强制结(conn, 水位事件时: str, 处理时: str, 规: dict | None = None) -> int:
    """强制切开口径：水位越过日界后，仍在途的昨日开腿强制结并旁路。

    日切只认事件时（进站事件时 ↔ 水位事件时的运营日关系），处理时仅作落库时刻。
    与成对写闸共用状态翻转闸，保证同一对不会行程与旁路双落。
    """
    n = 0
    规 = 规 if 规 is not None else 日界.取站规(conn)
    for leg in list(conn.execute("SELECT * FROM 开腿账 WHERE 状态='在途'")):
        if not 日界.应强制结(conn, leg["进站事件时"], 水位事件时, 规):
            continue
        if _状态翻转(conn, leg["开腿键"], "在途", "日界强制结", 处理时) == 0:
            continue
        conn.execute(
            "UPDATE 刷卡点 SET 命运=? WHERE 事件编号=? AND 命运='已开腿'",
            ("已旁路", leg["进站事件编号"]),
        )
        conn.execute(
            "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
            (
                "日界禁跨",
                leg["卡号"],
                leg["进站事件编号"],
                json.dumps(
                    {
                        "开腿键": leg["开腿键"],
                        "进站事件时": leg["进站事件编号"],
                        "进站日": 日界.事件日(leg["进站事件时"], 规),
                        "水位": 水位事件时,
                        "水位日": 日界.事件日(水位事件时, 规),
                        "日界架构": 规.get("日界架构", 日界.当前架构),
                    },
                    ensure_ascii=False,
                ),
                处理时,
            ),
        )
        n += 1
    return n


def 日界强制结(conn, 开腿, 出站事件编号: str, 水位事件时: str, 处理时: str, 规: dict) -> bool:
    """装载主链上即时发现的跨日：先把进站腿按日界强制结打旁路。

    返回 True 表示本腿由本次调用落定（出站侧随后走孤儿/新日规则）；
    False 表示腿已被并发/前置流程落定，调用方不得再写。
    """
    if _状态翻转(conn, 开腿["开腿键"], "在途", "日界强制结", 处理时) == 0:
        return False
    conn.execute(
        "UPDATE 刷卡点 SET 命运=? WHERE 事件编号=? AND 命运='已开腿'",
        ("已旁路", 开腿["进站事件编号"]),
    )
    conn.execute(
        "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
        (
            "日界禁跨",
            开腿["卡号"],
            开腿["进站事件编号"],
            json.dumps(
                {
                    "开腿键": 开腿["开腿键"],
                    "进站事件时": 开腿["进站事件时"],
                    "进站日": 日界.事件日(开腿["进站事件时"], 规),
                    "触发出站": 出站事件编号,
                    "水位": 水位事件时,
                    "出站日": 日界.事件日(水位事件时, 规),
                    "日界架构": 规.get("日界架构", 日界.当前架构),
                },
                ensure_ascii=False,
            ),
            处理时,
        ),
    )
    return True


def _状态翻转(conn, 开腿键: str, 旧态: str, 新态: str, 处理时: str) -> int:
    """成对写闸：开腿状态只允许单方向、单落一次。返回影响行数 0 即已被别处落定。"""
    cur = conn.execute(
        "UPDATE 开腿账 SET 状态=?, 更新处理时=? WHERE 开腿键=? AND 状态=?",
        (新态, 处理时, 开腿键, 旧态),
    )
    return cur.rowcount


def 成对写出站(conn, 开腿, 出站事件编号: str, 出站站点键: str, 出站事件时: str, 处理时: str,
            规: dict | None = None) -> str:
    """同日成对写一笔行程。调用前必须已通过日界裁决（同日 valid）。

    状态翻转带 在途 条件：腿一旦被日界/超时/重复进站旁路，成对写必然 0 行，
    从根上杜绝同一对既写行程又写旁路的双落。
    """
    if _状态翻转(conn, 开腿["开腿键"], "在途", "已成对", 处理时) == 0:
        raise RuntimeError(f"开腿{开腿['开腿键']}已被落定，禁止成对双写")

    规 = 规 if 规 is not None else 日界.取站规(conn)
    行程键 = f"行-{开腿['进站事件编号']}-{出站事件编号}"
    历时 = max(0, 时间.差秒(开腿["进站事件时"], 出站事件时))
    进站日 = 日界.事件日(开腿["进站事件时"], 规)
    出站日 = 日界.事件日(出站事件时, 规)
    跨日 = 1 if 进站日 != 出站日 else 0
    conn.execute(
        """INSERT INTO 行程账(行程键,卡号,进站事件编号,出站事件编号,进站站点键,出站站点键,
           进站事件时,出站事件时,历时秒,进站日,出站日,是否跨日,日界架构,状态,版本,处理时)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,'已成对',1,?)""",
        (
            行程键,
            开腿["卡号"],
            开腿["进站事件编号"],
            出站事件编号,
            开腿["进站站点键"],
            出站站点键,
            开腿["进站事件时"],
            出站事件时,
            历时,
            进站日,
            出站日,
            跨日,
            规.get("日界架构", 日界.当前架构),
            处理时,
        ),
    )
    conn.execute(
        "UPDATE 刷卡点 SET 命运=?, 行程键=? WHERE 事件编号 IN (?,?)",
        ("已成对", 行程键, 开腿["进站事件编号"], 出站事件编号),
    )
    return 行程键
